import { z } from "zod";

export const chatInputSchema = z
  .object({
    messages: z
      .array(
        z.object({
          role: z.enum(["user", "assistant"]),
          content: z.string().trim().min(1).max(1200),
        }),
      )
      .min(1)
      .max(10),
  })
  .refine((data) => data.messages.at(-1)?.role === "user", "ข้อความสุดท้ายต้องมาจากผู้ใช้")
  .refine(
    (data) => data.messages.reduce((n, m) => n + m.content.length, 0) <= 6000,
    "บทสนทนายาวเกินไป",
  );

